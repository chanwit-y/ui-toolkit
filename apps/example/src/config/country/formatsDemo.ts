import type { Bin, Container, DataTableColumnDef } from "@gummy-ui/ui";

/**
 * Cell formats demo page (`/formats`). A column's `format` tells the table how
 * to show its raw value — the engine formats it with `Intl` in the app's
 * locale (`<LocaleProvider>` / `project.locale`, default the browser's), so a
 * config no longer needs display strings from the API:
 *
 * - **number / currency / percent** — grouped digits, an ISO currency, a ratio
 *   (`0.027` → `2.7%`) or a whole number (`of: 100`); numeric formats align
 *   the column to the end unless `align` says otherwise;
 * - **date / datetime** — the locale's medium style in an optional IANA zone,
 *   or a dayjs `pattern` (`useDateFormat` still works as the date alias);
 * - **boolean** — `trueLabel` / `falseLabel`;
 * - the **search box** matches the formatted text too (`1,2` finds `1,234`, `Coastal` a boolean label),
 *   sorting and the column filter keep the raw value, and `{{value}}` in an
 *   `html` template is the formatted text;
 * - the **editable table** formats its cells in read mode; the editor gets the
 *   raw value.
 *
 * The figures (`population`, `area_km2`, `gdp_usd`, `growth`, `landlocked`)
 * are generated by the mock API and are not real.
 */
const section = (text: string, caption: string): Bin[] => [
  {
    sm: "12", md: "12", lg: "12", xl: "12",
    type: "typography",
    element: { text, variant: "subtitle1", weight: "medium" },
  },
  {
    sm: "12", md: "12", lg: "12", xl: "12",
    type: "typography",
    element: { text: caption, variant: "body2", color: "gray" },
  },
];

const countriesApi = {
  name: "countries",
  paths: ["data"],
  body: {
    collectionId: { type: "value", key: "collectionId", value: "691e9963992636eb1560eadb" },
    offset: { type: "value", key: "offset", value: 0 },
    limit: { type: "value", key: "limit", value: 100 },
  },
};

const column = (accessor: string, header: string, extra: Partial<DataTableColumnDef> = {}): DataTableColumnDef => ({
  accessor,
  header,
  enableSorting: true,
  enableColumnFilter: false,
  ...extra,
});

const table = (name: string, title: string, columns: DataTableColumnDef[], extra: Record<string, unknown> = {}): Bin => ({
  sm: "12", md: "12", lg: "12", xl: "12",
  type: "datatable",
  justifySelf: "stretch",
  alignSelf: "start",
  element: { name, title, columns, api: countriesApi, canSearch: false, ...extra } as Bin["element"],
});

